    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        String cpf = txtCpf.getText().trim();
    
        // Validação básica se o campo CPF estiver vazio
        if (cpf.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o CPF usado na inscrição para poder cancelar!");
            return;
        }

        Função funcao = (Função) cbbFuncao.getSelectedItem();

        if (funcao == null || funcao.getId() == 0) {
            JOptionPane.showMessageDialog(this,
                "Selecione a função que deseja cancelar!");
            return;
        }
        
        // Caixa de diálogo perguntando "Tem certeza?" para evitar cliques por engano
        int confirmacao = JOptionPane.showConfirmDialog(this, 
                "Tem certeza que deseja cancelar sua participação neste evento?", 
                "Confirmar Cancelamento", 
                JOptionPane.YES_NO_OPTION);

        if (confirmacao == JOptionPane.YES_OPTION) {
            ParticipaçãoDAO dao = new ParticipaçãoDAO();
            dao.cancelarParticipacao(cpf, this.evento.getId(), funcao.getId());
        }
    }//GEN-LAST:event_btnCancelarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // 1. Captura os campos fixos da tela
        String cpf = txtCpf.getText();
        String data = txtData.getText(); 

        if (cpf.isEmpty() || data.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha o CPF e a Data!");
            return;
        }
        
        Doação d = new Doação(); 
        d.setUsuCpf(cpf);
        d.setData(data);
        d.setEvento(this.evento); // Passa o evento atual recebido no construtor
        
        Função funcaoSelecionada = (Função) cbbFuncao.getSelectedItem();
        if (funcaoSelecionada.getId() == 0) {
            JOptionPane.showMessageDialog(this, "Selecione uma função válida!");
            return;
        }
        d.setFunção(funcaoSelecionada);
        d.setDescricao("Função atribuída: " + funcaoSelecionada.getNome());
        
        // 3. Com o "d" totalmente montado, enviamos ele para o DAO salvar no banco
        ParticipaçãoDAO dao = new ParticipaçãoDAO();
        dao.escolherCargo(d); // <--- Passando o d preenchido para o banco
    
    }//GEN-LAST:event_btnSalvarActionPerformed


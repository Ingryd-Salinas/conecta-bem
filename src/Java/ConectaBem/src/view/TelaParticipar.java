    //Método que preenche a combo box com dados do banco
    public void carregarComboBoxFuncoes() {

        // Limpa e Povoa o Combo de Funções
        cbbFuncao.removeAllItems();
        
        model.Função placeholder = new model.Função();
        placeholder.setNome("Selecione");
        placeholder.setId(0);
        cbbFuncao.addItem(placeholder); // Adiciona o objeto inicial seguro
        
        DAO.FunçãoDAO dao = new DAO.FunçãoDAO();
        for (model.Função f : dao.listarTodas()) {
            cbbFuncao.addItem(f); // Alimenta com os dados vindos do banco
        }
    }
    

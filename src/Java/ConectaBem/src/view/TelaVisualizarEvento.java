    private void btnDoarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDoarActionPerformed
        Evento eventoSelecionado = obterEventoSelecionado();

        if (eventoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um evento primeiro!");
            return;
        }
    
        // 1. Cria a instância do JPanel passando o evento
        TelaDoar tela = new TelaDoar(eventoSelecionado);
    
        // 2. Cria uma janela JDialog flutuante passando 'this' (a tela atual) como dona
        // O parâmetro 'true' ativa o modo MODAL (bloqueia a tela de trás)
        javax.swing.JDialog janelaPopUp = new javax.swing.JDialog(this, " ", true);
    
        // 3. Coloca o painel dentro da nova janela
        janelaPopUp.add(tela);
    
        // 4. Ajusta o tamanho da janela de acordo com o tamanho do painel
        janelaPopUp.pack();
    
        // 5. Centraliza o pop-up no meio do monitor
        janelaPopUp.setLocationRelativeTo(this);
    
        // 6. Exibe a janela na tela
        janelaPopUp.setVisible(true);
    }//GEN-LAST:event_btnDoarActionPerformed


    public Evento obterEventoSelecionado() {

        int linha = tblEvento.getSelectedRow();

        if (linha == -1)
            return null; // Nenhuma linha foi clicada
    

        Evento evento = new Evento();
        // Pega os dados diretamente das colunas da JTable
        evento.setId(Integer.parseInt(tblEvento.getValueAt(linha, 0).toString()));
        evento.setNome(tblEvento.getValueAt(linha, 1).toString());
        evento.setStatus(tblEvento.getValueAt(linha, 2).toString());
        evento.setData(tblEvento.getValueAt(linha, 3).toString());
        evento.setRua(tblEvento.getValueAt(linha, 4).toString());
        evento.setNumero(tblEvento.getValueAt(linha, 5).toString());
        evento.setBairro(tblEvento.getValueAt(linha, 6).toString());
        evento.setCidade(tblEvento.getValueAt(linha, 7).toString());
        evento.setUf(tblEvento.getValueAt(linha, 8).toString());

        return evento;
    }
    
    //Método para criar o object, ou seja, insere linhas na tabela com dados do BD
    public void preencherTabela(){
        // 1. Instancia o DAO para buscar os dados do MySQL
        EventoDAO dao = new EventoDAO();
        ArrayList<Evento> lista = dao.listarTodos();
    
        // 2. Captura o modelo da sua JTable tblEvento
        DefaultTableModel modelo = (DefaultTableModel) tblEvento.getModel();
    
        // 3. Limpa a tabela para não duplicar os dados caso clique duas vezes
        modelo.setNumRows(0);
    
        // 4. Varre o ArrayList criando o Object[] para cada evento
        for (Evento e : lista) {
            Object[] linha = new Object[]{
                e.getId(),
                e.getNome(),
                e.getStatus(),
                e.getData(),
                e.getRua(),
                e.getNumero(),
                e.getBairro(),
                e.getCidade(),
                e.getUf()
            };
        
            // 5. Adiciona a linha preenchida na tabela visual
            modelo.addRow(linha);
        }//fim for
    }//fim preencherTabela
    
    private void atualizarTabela(String busca){

        DAO.EventoDAO dao = new DAO.EventoDAO();

        ArrayList<Evento> lista = dao.listarBusca(busca);

        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEvento.getModel();

        modelo.setNumRows(0);

        for(model.Evento e : lista){

            modelo.addRow(new Object[]{
                e.getId(),
                e.getNome(),
                e.getStatus(),
                e.getData(),
                e.getRua(),
                e.getNumero(),
                e.getBairro(),
                e.getCidade(),
                e.getUf()
            });

        }

    }
    

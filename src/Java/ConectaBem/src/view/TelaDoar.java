    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        // 1. Pega os campos fixos da tela
        String cpf = txtCpf.getText().trim();
        String data = txtData.getText().trim();

        if (cpf.isEmpty() || data.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha o CPF e a Data!");
            return;
        }

        // ==========================================================
        // AQUI NASCE O "d": Criamos o objeto Doação na memória
        // ==========================================================
        Doação d = new Doação(); 
        d.setUsuCpf(cpf);
        d.setData(data);
        d.setEvento(this.evento); // Passa o evento atual recebido no construtor
        
        // 1. Verifica se é Dinheiro
        if (rdbDinheiro.isSelected()) {
            d.setValor(Double.parseDouble(txtValor.getText().trim()));
            d.setDescricao("Doação em Dinheiro");

        // 2. SE NÃO FOR DINHEIRO, verifica se é Insumo
        } else if (rdbInsumo.isSelected()) {
            Insumo insumoSelecionado = (Insumo) cbbInsumo.getSelectedItem();
            if (insumoSelecionado.getId() == 0) {
                JOptionPane.showMessageDialog(this, "Selecione um Insumo válido!");
                return;
            }
            d.setInsumo(insumoSelecionado);
            int quantidade = (int) spnQtdInsumo.getValue();
            d.setQuantidade(quantidade);
            d.setDescricao("Doação de Insumo: " + insumoSelecionado.getNome());
            

        // 3. SE NÃO FOR NENHUM DOS DOIS, verifica se é Utensílio
        } else if (rdbUtensilio.isSelected()) {
            Utensilio utensilioSelecionado = (Utensilio) cbbUtensilios.getSelectedItem();
            if (utensilioSelecionado.getId() == 0) {
                JOptionPane.showMessageDialog(this, "Selecione um Utensílio válido!");
                return;
            }
            d.setUtensilio(utensilioSelecionado);
            int quantidade = (int) spnQtdUtensilio.getValue();
            d.setQuantidade(quantidade);
            d.setDescricao("Doação de Utensílio: " + utensilioSelecionado.getNome());

        // 4. SE NÃO FOR NENHUM, avisa o usuário
        } else {
            JOptionPane.showMessageDialog(this, "Por favor, selecione um Tipo de Doação!");
            return;
        }
        
        // 3. Com o "d" totalmente montado, enviamos ele para o DAO salvar no banco
        DoaçãoDAO dao = new DoaçãoDAO();
        dao.registrarDoacao(d); // <--- Passando o d preenchido para o banco
    }//GEN-LAST:event_btnSalvarActionPerformed


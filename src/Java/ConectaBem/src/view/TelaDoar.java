    public void carregarCombos() {
        
        // 1. Limpa e Povoa o Combo de Insumos
        cbbInsumo.removeAllItems();
    
        model.Insumo placeholderInsumo = new model.Insumo();
        placeholderInsumo.setNome("Selecione");
        placeholderInsumo.setId(0);
        cbbInsumo.addItem(placeholderInsumo); // Adiciona o objeto inicial seguro

        DAO.InsumoDAO insDAO = new DAO.InsumoDAO();
        for (model.Insumo i : insDAO.listarTodos()) 
            cbbInsumo.addItem(i); // Alimenta com os dados vindos do banco

        // 2. Limpa e Povoa o Combo de Utensílios
        cbbUtensilios.removeAllItems();
    
        model.Utensilio placeholderUte = new model.Utensilio();
        placeholderUte.setNome("Selecione");
        placeholderUte.setId(0);
        cbbUtensilios.addItem(placeholderUte); // Adiciona o objeto inicial seguro

        DAO.UtensilioDAO uteDAO = new DAO.UtensilioDAO();
        for (model.Utensilio u : uteDAO.listarTodos()) 
            cbbUtensilios.addItem(u); // Alimenta com os dados vindos do banco
    
    
    }

